SEVERITY_LABELS = {
    "en": {"critical": "Must fix", "high": "Fix before applying", "medium": "Check this", "info": "Do this once"},
    "hi": {"critical": "ज़रूर ठीक करें", "high": "आवेदन से पहले ठीक करें", "medium": "जाँच लें", "info": "एक बार ज़रूर करें"},
}


class _SafeDict(dict):
    def __missing__(self, key):
        return "{" + key + "}"


def _fmt(text: str, params: dict) -> str:
    return text.format_map(_SafeDict(params))


def render_issue(issue: dict, lang: str = "en") -> dict:
    """Return {title, why, fix[]} for an issue in `lang` ('en' or 'hi')."""
    lang = lang if lang in ("en", "hi") else "en"
    params = dict(issue.get("params", {}))
    if "doc" in params:
        params["doc"] = DOC_LABELS[lang].get(params["doc"], params["doc"])
    if "relation" in params:
        params["relation"] = RELATIONS[lang].get(params["relation"], params["relation"])

    code = issue["code"]
    if code == "name_mismatch":
        doc_key = issue["params"]["doc"]
        title = _fmt(NAME_TITLES[lang][issue["params"]["kind"]], params)
        why = _fmt(NAME_WHY[lang], params)
        fix = [_fmt(s, params) for s in NAME_FIX[lang].get(doc_key, [])]
    else:
        block = ISSUES[code][lang]
        title = _fmt(block["title"], params)
        why = _fmt(block["why"], params)
        fix = [_fmt(s, params) for s in block["fix"]]
    if title and title[0].islower():
        title = title[0].upper() + title[1:]
    return {"title": title, "why": why, "fix": fix,
            "severity_label": SEVERITY_LABELS[lang][issue["severity"]]}
